// Builds data/fields/cassino-monastery-1944.yaml: the 4th Indian Division's night attack along
// Snakeshead Ridge on Point 593 and the abbey, 17-18 February 1944, on the field map at 10 m a
// hex. Run from this folder after editing: node make_cassino_monastery_field.mjs
//
// Sources, all public domain or plain fact, and the drawing is ours: the plain facts of the
// battle as the official histories give them and as they are summarised publicly. On the night
// of 17 February the 4/6th Rajputana Rifles attacked Point 593 along the narrow Snakeshead Ridge,
// the Royal Sussex in reserve, while the 1/9th and 1/2nd Gurkhas went down across the slopes for
// Point 444 and the abbey's hill; German paratroops held the rocky tops and the abbey's ruins,
// bombed two days before. The ground (cassino_massif.mjs) is drawn by hand, not traced from any
// map, and approximate; the deployment is the attack going in, in our own words, with round
// numbers for play.
import { N, S, unit, writeField, at } from "./field_lib.mjs";
import { COLS, ROWS, P593, P444, ABBEY, massif, MASSIF_NOTES, heldSnakeshead, posts, PARA, MG, GERMAN_MORTARS, SIZE_LINE } from "./cassino_massif.mjs";

const grid = massif();
const AL = { side: 0, facing: S }, DE = { side: 1, facing: N };
const SEPOY = { quality: "veteran", weapon: "rifle_service", kit: "ww2_rifleman", formation: "extended", mounted: false };
const units = [
  at("4/6th Rajputana Rifles (along Snakeshead Ridge)", AL, 450, SEPOY, 15, [P593[0] + 2, 12], S),
  at("1st Royal Sussex (three companies, with the Rajputanas)", AL, 150, SEPOY, 15, [P593[0] - 22, 6], S),
  at("1/9th Gurkha Rifles (across the slopes for Point 444)", AL, 450, SEPOY, 20, [P444[0] - 4, 40], S),
  at("1/2nd Gurkha Rifles (down for the abbey's hill)", AL, 450, SEPOY, 20, [ABBEY[0] - 10, 68], S),
  at("German paratroops on Point 593", DE, 120, PARA, 10, [P593[0], P593[1] + 2], N),
  ...heldSnakeshead(),
  at("German machine guns (Point 593)", DE, 10, MG, 2, [P593[0] + 8, P593[1] + 4], N),
  at("German machine guns (the abbey)", DE, 15, MG, 3, [ABBEY[0] - 14, ABBEY[1] - 2], 2),
];

writeField({
  phases: [   // an exchange is about a minute; times and sources in the project's battle-phases research (round 2), rounded; (est.) marks an estimate
    { name: "For Point 593", at: 1, note: "Midnight: the Rajputana Rifles and three Sussex companies go for Point 593." },
    { name: "The Gurkhas go in", at: 121, note: "Two hours later, as planned: the 1/2nd and 1/9th Gurkhas go down the slopes for the abbey (the plan's time).", arrive: ["1/9th Gurkha Rifles (across the slopes for Point 444)", "1/2nd Gurkha Rifles (down for the abbey's hill)"] },
    { name: "A standstill", at: 211, note: "By 03:30 the attack is at a standstill." },
    { name: "A fourth company", at: 271, note: "04:30: a fourth Rajputana company is thrown in and fails to regain the summit; before dawn a Gurkha company gets a lodgement on Point 445." },
  ],
  ends: { at: 418, why: "the attack had failed by dawn: sunrise about 06:57 Central European time, worked out for the place and day, from midnight" },
  objective: { at: P593, side: 0, name: "Point 593", radius: 4 },
  id: "cassino-monastery-1944", name: "Snakeshead Ridge and the abbey, 17-18 February 1944", sides: ["Allies", "Germans"], table: "owens-wwii",
  travel: { map: "cassino-1944", place: "Point 593 (Monte Calvario)", within: 1, sides: ["Allies", "Germans"] },
  weather: "{cond: fair, wind: breeze, dir: N, light: night, ground: {mud: 1, snow: 0}}",
  grid, units,
  hexWorks: posts(units),
  support: [
    { name: "Field guns (25-pounders)", side: 0, kind: "field", tubes: 24 },
    { name: "Medium guns", side: 0, kind: "howitzer", tubes: 8 },
    { name: "3-inch mortars", side: 0, kind: "mortar", tubes: 6 },
    GERMAN_MORTARS,
    { name: "German guns in the Liri valley", side: 1, kind: "field", tubes: 8 },
  ],
  header: [
    `Snakeshead Ridge, Point 593 and the abbey of Monte Cassino on the night of 17-18 February 1944, at 10 m a hex: ${COLS} x ${ROWS}`,
    SIZE_LINE,
    "upper left, Snakeshead Ridge running down to the south-east past Point 444 to the abbey's",
    "ruins at the lower right, Phantom Ridge off to the west, steep scrubby slopes and gullies.",
    "Generated by tools/maps/make_cassino_monastery_field.mjs (the ground is cassino_massif.mjs):",
    "edit them and re-run it rather than this file.",
    ...MASSIF_NOTES,
    "A dark night on the mountain: no one sees beyond 55 yards (50 m) without illumination. The abbey is rubble.",
    "",
    "What happened, briefly: after the abbey was bombed on 15 February, the 4th Indian Division",
    "attacked along the narrow ridge from the north. The Royal Sussex had already attacked Point 593",
    "on the two nights before, taking its ruined fort on the second and giving it up before dawn, at a",
    "cost of 162 of their 313 men (Holmes, The Tiger Triumphs); at midnight on the 17th the Rajputana Rifles, with three",
    "Sussex companies, went for it, and two hours later the Gurkhas down the slopes for the abbey",
    "(by Point 445, says The Tiger Triumphs; Point 444 in other accounts), into minefields, thorn scrub and",
    "machine-gun fire from the paratroops on the tops. By dawn on the 18th the attack had failed",
    "with heavy loss, and it was called off.",
  ],
});
