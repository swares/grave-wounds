// Builds data/fields/albuera-1811.yaml: the field of Albuera, 16 May 1811, on the field map at
// 10 m a hex. Run from this folder after editing: node make_albuera_field.mjs (no packages needed).
//
// Sources, all plain fact, and the drawing is ours: the allied army stood on the low ridge west
// of the Albuera stream, with the village and its bridge at the north end of the fighting;
// Soult feinted at the village and sent his main force round through the olive woods, across
// the brooks, onto the heights south of the allied line, where the battle was decided. The
// village, the stream, the woods and the heights are drawn by hand to that shape, not traced
// from any map, and are approximate. The field runs from the village south over the heights:
// the allied line north of the village is off the map. The deployment is the moment Soult's
// flank attack came on, in our own words; numbers are round figures for play, the guns among them.
import { N, S, wobble, groundGrid, unit, writeField } from "./field_lib.mjs";

const COLS = 150, ROWS = 230;                 // 1500 m east to west, about 2000 m north to south
const stream = r => 104 + wobble(r / 3, 0.6, 2.4) + (r > 60 ? (r - 60) * 0.15 : 0);   // the Albuera, then the Nogales brook to the south-east
function kind(c, r){
  if (Math.abs(c - stream(r)) <= 1.2) return "m";                                   // the stream and its wet banks
  if (c >= 92 && c <= 118 && r >= 4 && r <= 30) return "r";                          // La Albuera village and its bridge
  if (c > stream(r) + 4 && r > 90 && r < 215 && c < 148) return "F";                // olive woods across the brooks, hiding the flank march
  if (c >= 40 && c < stream(r) - 3 && r > 120 && r < 190 + wobble(c / 2, 1.2, 0.3)) return "h";   // the heights south of the allied line
  if (c >= 30 && c < stream(r) - 6 && r < 120) return "h";                          // the allied ridge
  return ".";
}
const grid = groundGrid(COLS, ROWS, kind);

// ---------- the armies (pos is the middle of the front row) ----------
// The allies have wheeled to face the attack from the south; the French come up from the south.
const ALLY = { side: 0, facing: S }, FR = { side: 1, facing: N };
const LINE = { quality: "regular", weapon: "musket_smoothbore", kit: "none", formation: "close", mounted: false };
const HORSE = { quality: "regular", weapon: "saber", kit: "dragoon_helmet", formation: "close", mounted: true };
const GUNS = { quality: "regular", weapon: "artillery_smoothbore", kit: "none", formation: "battery", mounted: false };   // ten crew to a gun
const units = [
  unit("Zayas's Spanish", ALLY, 4000, LINE, [70, 45, 140]),
  unit("Colborne's brigade", ALLY, 1600, { ...LINE, quality: "veteran" }, [40, 5, 142]),
  unit("Hoghton's and Abercrombie's brigades", ALLY, 3500, { ...LINE, quality: "veteran" }, [70, 45, 128]),
  unit("Allied cavalry (Lumley)", ALLY, 2000, HORSE, [25, 75, 118]),
  unit("Cole's division (coming up)", ALLY, 5000, LINE, [60, 10, 110]),
  unit("Hamilton's Portuguese (reserve)", ALLY, 5000, LINE, [60, 35, 70]),
  unit("Alten's Germans in the village", ALLY, 1000, { ...LINE, quality: "veteran" }, [20, 92, 32]),
  unit("Girard's division, in column", FR, 4500, { ...LINE, quality: "veteran" }, [30, 60, 175]),
  unit("Gazan's division, in column", FR, 4000, LINE, [30, 92, 182]),
  unit("Werlé's brigade (reserve)", FR, 3500, LINE, [30, 70, 205]),
  unit("Polish lancers and hussars", FR, 1500, { ...HORSE, quality: "veteran", weapon: "lance" }, [25, 10, 172]),
  unit("Latour-Maubourg's dragoons", FR, 2000, HORSE, [30, 40, 222]),
  unit("French guns with the columns", FR, 200, GUNS, [10, 50, 192]),
  unit("Allied guns on the heights", ALLY, 120, GUNS, [6, 40, 136]),
  // Godinot's feint at the village comes from the east across the stream: facing 3 (west, a
  // little south), so its front runs north-west to south-east; pos is the middle of the front.
  { name: "Godinot's brigade (feint at the village)", side: 1, facing: 3, men: 3500, ...LINE, width: 25, pos: [128, 40] },
];

writeField({
  objective: { at: [40, 136], side: 1, name: "the heights south of the allied line" },
  id: "albuera-1811", name: "Albuera, 16 May 1811", sides: ["Allies", "French"], table: "peninsular-1808-14-all-hits",
  travel: { map: "albuera-1811", place: "La Albuera", within: 2, sides: ["Allies", "France"] },
  weather: "{cond: overcast, wind: breeze, ground: {mud: 0, snow: 0}}",
  grid, units,
  header: [
    `The field of Albuera, 16 May 1811 (Gregorian), at 10 m a hex: ${COLS} x ${ROWS} hexes, about 1500 m`,
    "east to west and 2000 m north to south, north at the top: from the village south over the",
    "heights where the battle was decided. The allied line north of the village is off the map.",
    "Generated by tools/maps/make_albuera_field.mjs: edit that file and re-run it rather than this one.",
    "The village, the stream, the woods and the heights are drawn by hand to the shape the accounts",
    "give, not traced from any map; the deployment is the moment of Soult's flank attack, in our",
    "own words, with round numbers for play.",
    "",
    "What happened, briefly: Godinot's brigade made a show against the village while Girard's",
    "and Gazan's divisions, screened by the olive woods, crossed the brooks and came up onto the",
    "heights in heavy columns. Zayas's Spaniards turned to face them and held. Colborne's brigade",
    "came up on their right and was caught in line by the Polish lancers and hussars in a sudden",
    "hailstorm and nearly destroyed. Hoghton's and Abercrombie's brigades took the Spaniards'",
    "place and stood exchanging volleys at short range until most of their men were down; Cole's",
    "division, coming up on the right, drove the French off the heights. The hailstorm is not",
    "set: the GM can bring it in (storm) for the lancers' charge. The guns: 20 French with the",
    "columns and 12 allied on the heights (round figures).",
  ],
});
