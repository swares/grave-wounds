// - the rest by name where the name says what stands there (A Company, 1/9th Gurkha Rifles,
//   Colborne's brigade) and it is within a step of its numbers; else by men on one scale for
//   every period: up to 12 section, 60 platoon, 250 company, 1,000 battalion, 3,000 regiment,
//   6,000 brigade, more division. Detachments of a named formation ("29th Regiment in the south
