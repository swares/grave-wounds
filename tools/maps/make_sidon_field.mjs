// Builds data/fields/sidon-1253.yaml: the raid on Sidon, 1253, at the town's landward wall, on the
// field map at 10 m a hex. Run from this folder after editing: node make_sidon_field.mjs
// (no packages needed).
//
// This field is drawn with EAST AT THE TOP, as medieval maps were, so the attack comes down
// the page: the town and the sea are at the bottom (west), north is on the left.
//
// Sources, all plain fact, and the drawing is ours: Sidon's walls were being rebuilt in 1253;
// the mass graves were found in the ditch along the town's eastern, landward edge, by a fortified
// gateway with a crossing over the ditch, near the mound where the land castle stands. The wall,
// its unfinished stretch, the ditch, the gate and the ground are drawn by hand to that, not traced
// from any map, and are approximate. The deployment is our own reading, in our own words; the
// written record of the raid is thin, and the numbers are guesses for play.
import { N, S, wobble, groundGrid, unit, writeField } from "./field_lib.mjs";

const COLS = 110, ROWS = 90;                  // 1100 m north to south (left to right), about 780 m east to west
const WALL_ROW = 60;                          // the town is below this row (to the west)
const GATE_COL = 50;
const GAP = [36, 46];                         // the stretch of wall not yet built: only its footing, a low bank
function kind(c, r){
  if (r >= WALL_ROW && c >= 72 && c <= 88 && r <= 76) return "h";              // the old mound where the land castle stands
  if (r >= WALL_ROW) return "r";                                              // the town: streets, houses, yards
  if (r < 8 + wobble(c / 3, 0.4, 1.8)) return "h";                            // the first foothills, to the east
  if ((r > 30 && r < 42 && c > 8 && c < 30) || (r > 22 && r < 34 && c > 70 && c < 98)) return "F";   // orchards and gardens
  return ".";
}
const grid = groundGrid(COLS, ROWS, kind);

// Along the wall line: every side between a row-60 hex and the row-59 hexes above it (east of
// it), the town side first. On an even row a hex's upper neighbours are (c-1, r-1) and (c, r-1).
const wall = [], bank = [], ditch = [], gate = [];
for (let c = 0; c < COLS; c++){
  for (const up of [[c - 1, WALL_ROW - 1], [c, WALL_ROW - 1]]){
    if (up[0] < 0) continue;
    const side = [[c, WALL_ROW], up];
    if (c === GATE_COL && up[0] === c){ gate.push(side); continue }   // the gateway, with its crossing over the ditch
    ditch.push(side);
    (c >= GAP[0] && c <= GAP[1] ? bank : wall).push(side);
  }
}

// ---------- the armies (pos is the middle of the front row; "north" on the page is east) ----------
const FRANK = { side: 0, facing: N }, DAMASCUS = { side: 1, facing: S };
const units = [
  unit("Crossbowmen of the garrison", FRANK, 300, { quality: "regular", weapon: "crossbow", kit: "hauberk", formation: "open", mounted: false }, [30, 26, 61]),
  unit("Garrison sergeants", FRANK, 500, { quality: "regular", weapon: "spear", kit: "hauberk", formation: "close", mounted: false }, [25, 28, 64]),
  unit("Knights", FRANK, 100, { quality: "veteran", weapon: "sword", kit: "hauberk", formation: "close", mounted: true }, [5, 38, 67]),
  unit("Builders and townsmen", FRANK, 600, { quality: "green", weapon: "axe", kit: "none", formation: "close", mounted: false }, [30, 26, 70]),
  unit("Horse archers", DAMASCUS, 1500, { quality: "veteran", weapon: "bow", kit: "leather", formation: "open", mounted: true }, [40, 22, 30]),
  unit("Heavy horse", DAMASCUS, 800, { quality: "veteran", weapon: "spear", kit: "hauberk", formation: "close", mounted: true }, [20, 32, 24]),
  unit("Foot", DAMASCUS, 1500, { quality: "regular", weapon: "sword", kit: "gambeson", formation: "close", mounted: false }, [40, 22, 20]),
];

writeField({
  id: "sidon-1253", name: "Sidon, 1253", sides: ["Franks", "Damascenes"], table: "sidon-1253-all-hits",
  travel: { map: "sidon-1253", place: "Sidon", within: 1, sides: ["Franks", "Damascus"] },
  weather: "{cond: fair, wind: calm, ground: {mud: 0, snow: 0}}",
  grid, units, edgeWorks: { ditch, wall, bank, gate },
  header: [
    `The raid on Sidon, 1253, at the town's landward wall, at 10 m a hex: ${COLS} x ${ROWS} hexes, about`,
    "1100 m north to south and 780 m east to west, with EAST AT THE TOP (north on the left), as",
    "medieval maps were drawn: the town and the sea are at the bottom.",
    "Generated by tools/maps/make_sidon_field.mjs: edit that file and re-run it rather than this one.",
    "The wall, its unfinished stretch, the ditch, the gate and the ground are drawn by hand to the",
    "excavators' description, not traced from any map; the deployment is our own reading, in our own",
    "words, and the numbers are guesses for play.",
    "",
    "What happened, briefly: an army from Damascus came down on Sidon while its walls were being",
    "rebuilt. The garrison could not hold the unfinished line; the attackers broke in, killed",
    "hundreds and carried others off, and some of the garrison held out in the sea castle. The",
    "dead found in the town ditch were young men and boys, many cut down from behind.",
  ],
});
