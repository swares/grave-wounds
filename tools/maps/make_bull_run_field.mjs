// Builds data/fields/bull-run-1861.yaml: Henry Hill at First Bull Run (Manassas), 21 July 1861, on
// the field map at 10 m a hex. Run from this folder after editing: node make_bull_run_field.mjs
// (no packages needed).
//
// Sources, all plain fact, and the drawing is ours: the afternoon's fight was on the broad top of
// Henry Hill, south of the Warrenton turnpike and Young's Branch, between the Sudley road on its
// west and the Robinson farm on its east, with pine woods along its south-east edge where
// Jackson's brigade formed, and Chinn Ridge across the Sudley road to the west. The hill, the
// branch, the woods and the ridge are drawn by hand to that shape, not traced from any map, and
// are approximate. The deployment is the early afternoon, when the Union batteries had been
// pushed onto the hill near the Henry house, in our own words; numbers are round figures for
// play, the guns among them. The two Union batteries are rifled (Ricketts's six 10-pounder
// Parrotts; Griffin's a mix, set rifled here); the Confederate guns, mostly 6-pounders and
// howitzers, are left smoothbore.
import { N, S, wobble, patch, groundGrid, unit, writeField } from "./field_lib.mjs";

const COLS = 140, ROWS = 130;                 // 1400 m east to west, about 1130 m north to south
const branch = c => 20 + wobble(c / 3, 1.7, 0.6);                    // Young's Branch, under the turnpike
function kind(c, r){
  if (Math.abs(r - branch(c)) <= 1.2) return "m";                    // the branch and its wet bottom
  if (r < branch(c) - 6 && patch(c, r, { cx: 75, cy: 0, rx: 38, ry: 12, a: 1.2, b: 0.3 })) return "h";   // Matthews Hill's southern slope, north of the turnpike
  if (c < 8 + wobble(r / 3, 0.9, 2.1) && r > 30 && r < 115) return "F";        // woods on Chinn Ridge
  if (patch(c, r, { cx: 10, cy: 72, rx: 9, ry: 40, a: 2.4, b: 0.8 })) return "h";                         // Chinn Ridge, west of the Sudley road
  if (r > 92 + wobble(c / 4, 0.4, 2.2) && c > 42 + wobble(r / 3, 1.0, 0.2)) return "F";   // the pines on the south-east edge of the plateau
  if (r > branch(c) + 8 && patch(c, r, { cx: 78, cy: 60, rx: 52, ry: 32, a: 0.6, b: 1.9 })) return "h";  // the broad top of Henry Hill
  return ".";
}
const grid = groundGrid(COLS, ROWS, kind);

// ---------- the armies (pos is the middle of the front row) ----------
const CSA = { side: 0, facing: N }, USA = { side: 1, facing: S };
const RIFLE = { quality: "green", weapon: "rifle_musket", kit: "none", formation: "close", mounted: false };
const GUNS = { quality: "regular", weapon: "artillery_acw", kit: "none", formation: "battery", mounted: false };   // ten crew to a gun
const units = [
  unit("Jackson's brigade", CSA, 2600, { ...RIFLE, quality: "regular" }, [40, 55, 88]),
  unit("33rd Virginia", CSA, 450, RIFLE, [10, 31, 80]),
  unit("Confederate guns (Imboden, Stanard, Pendleton)", CSA, 130, { ...GUNS }, [7, 74, 84]),
  unit("Hampton's Legion", CSA, 600, RIFLE, [15, 104, 70]),
  unit("Bee's and Bartow's men, rallied", CSA, 1000, RIFLE, [25, 82, 100]),
  unit("Stuart's cavalry", CSA, 300, { ...RIFLE, weapon: "saber", mounted: true, quality: "regular" }, [10, 12, 116]),
  unit("Ricketts's battery (10-pounder Parrotts)", USA, 70, { ...GUNS, guns: "rifled" }, [3, 62, 52]),
  unit("Griffin's battery (rifles and howitzers)", USA, 60, { ...GUNS, guns: "rifled" }, [3, 46, 54]),
  unit("11th New York (Fire Zouaves)", USA, 900, RIFLE, [22, 30, 48]),
  unit("US Marines", USA, 350, RIFLE, [9, 52, 46]),
  unit("14th Brooklyn", USA, 700, RIFLE, [18, 80, 46]),
  unit("Willcox's and Franklin's brigades", USA, 4000, RIFLE, [50, 30, 30]),
  unit("Sherman's brigade (coming over)", USA, 3000, RIFLE, [40, 80, 12]),
];

writeField({
  id: "bull-run-1861", name: "First Bull Run, 21 July 1861", sides: ["Confederates", "Union"], table: "acw-1861-all-hits",
  travel: { map: "bull-run-1861", place: "Henry Hill", within: 2, sides: ["Confederacy", "Union"] },
  weather: "{cond: fair, wind: calm, dir: SW, ground: {mud: 0, snow: 0}}",
  grid, units,
  header: [
    `Henry Hill at First Bull Run, 21 July 1861, at 10 m a hex: ${COLS} x ${ROWS} hexes, about 1400 m east`,
    "to west and 1130 m north to south, north at the top: the turnpike and Young's Branch along the",
    "north, the Sudley road down the west side, Chinn Ridge beyond it.",
    "Generated by tools/maps/make_bull_run_field.mjs: edit that file and re-run it rather than this one.",
    "The hill, the branch, the woods and the ridge are drawn by hand to the shape the accounts give,",
    "not traced from any map; the deployment is the early afternoon, in our own words, with round",
    "numbers for play.",
    "",
    "What happened, briefly: by noon the Union flank march had driven the Confederates off Matthews",
    "Hill and over the turnpike. Jackson's Virginians formed on the far edge of Henry Hill with",
    "their guns, and the broken brigades rallied behind them. McDowell pushed two regular batteries,",
    "Ricketts's and Griffin's, onto the hill near the Henry house with the Fire Zouaves and the",
    "Marines in support. The 33rd Virginia, in blue, came out of the woods by the Sudley road and",
    "shot down the gunners, and Stuart's horse rode into the Zouaves. The guns changed hands",
    "several times through the afternoon. Late in the day fresh Confederate brigades came up on",
    "Chinn Ridge to the west, and the Union line broke and streamed back over Bull Run. The day was",
    "very hot. Most men on both sides were in their first battle.",
  ],
});
