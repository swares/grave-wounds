// Builds data/fields/cowpens-1781.yaml: the field of Cowpens, 17 January 1781, on the field map at
// 10 m a hex. Run from this folder after editing: node make_cowpens_field.mjs (no packages needed).
//
// Sources, all plain fact, and the drawing is ours: the fight was in an open pasture of scattered
// trees along the Green River road, on a gentle slope rising away from the British to a low
// crest, with a second rise behind it where Morgan kept his horse, and wet ground on the flanks.
// The ground is drawn by hand to that shape, not traced from any map, and is approximate; the
// road runs up the middle of the field, which is drawn with north at the top and the British
// coming up from the south. The deployment is Morgan's three lines as most modern accounts give
// them, in our own words; numbers are round figures for play, the guns among them.
import { N, S, wobble, patch, groundGrid, unit, writeField } from "./field_lib.mjs";

const COLS = 120, ROWS = 100;                 // 1200 m east to west, about 870 m north to south
function kind(c, r){
  if (Math.abs(c - (8 + wobble(r / 2, 0.5, 1.4))) <= 2 || Math.abs(c - (112 + wobble(r / 2, 2.2, 0.3))) <= 2) return "m";   // the wet ravines on the flanks
  if (c < 6 || c > 115) return "F";                                     // the woods beyond them
  if (patch(c, r, { cx: 60, cy: 33, rx: 34, ry: 11, a: 1.1, b: 0.4 })) return "h";      // the low crest the Continentals held
  if (patch(c, r, { cx: 60, cy: 10, rx: 26, ry: 8, a: 0.2, b: 2.0 })) return "h";       // the rise behind, where the horse waited
  return ".";
}
const grid = groundGrid(COLS, ROWS, kind);

// ---------- the armies (pos is the middle of the front row) ----------
const US = { side: 0, facing: S }, GB = { side: 1, facing: N };
const RIFLES = { quality: "regular", weapon: "rifle_flintlock", kit: "none", formation: "open", mounted: false };
const MILITIA = { quality: "green", weapon: "rifle_flintlock", kit: "none", formation: "open", mounted: false };
const LINE = { quality: "regular", weapon: "musket_smoothbore", kit: "none", formation: "close", mounted: false };
const HORSE = { quality: "veteran", weapon: "saber", kit: "dragoon_helmet", formation: "close", mounted: true };
const GUNS = { quality: "regular", weapon: "artillery_smoothbore", kit: "none", formation: "battery", mounted: false };   // ten crew to a gun
const units = [
  unit("Riflemen skirmishing (McDowell, Cunningham)", US, 150, RIFLES, [40, 40, 62]),
  unit("Militia line (Pickens)", US, 900, MILITIA, [50, 35, 50]),
  unit("Continentals and Virginia men (Howard)", US, 550, { ...LINE, quality: "veteran" }, [28, 46, 36]),
  unit("Washington's horse", US, 150, HORSE, [8, 56, 16]),
  unit("Legion infantry", GB, 250, LINE, [8, 50, 84]),
  unit("7th Fusiliers", GB, 200, { ...LINE, quality: "green" }, [7, 60, 84]),
  unit("Light infantry", GB, 200, { ...LINE, formation: "open" }, [12, 36, 84]),
  unit("Grasshopper guns", GB, 20, GUNS, [1, 58, 87]),
  unit("71st Highlanders (reserve)", GB, 250, { ...LINE, quality: "veteran" }, [8, 54, 94]),
  unit("Legion dragoons, right", GB, 50, { ...HORSE, quality: "regular" }, [3, 28, 86]),
  unit("Legion dragoons, left", GB, 50, { ...HORSE, quality: "regular" }, [3, 74, 86]),
  unit("Legion dragoons (reserve)", GB, 150, { ...HORSE, quality: "regular" }, [5, 66, 95]),
];

writeField({
  phases: [   // an exchange is about a minute; times and sources in the project's battle-phases research (round 2), rounded; (est.) marks an estimate
    { name: "The British attack", at: 1, note: "About sunrise (about 07:00): Tarleton attacks at once after his night march." },
    { name: "In musket range", at: 4, note: "In under three minutes the British are within musket range of the militia." },
    { name: "The militia fall back", at: 13, note: "After 8 to 12 minutes of fire (est.) the militia fall back round the Continentals' left." },
    { name: "About-face and bayonets", at: 46, note: "07:45: the Continentals face about, halt, fire and charge with the bayonet; Washington's horse come in." },
    { name: "Over", at: 61, note: "By 08:00 the battle is over." },
  ],
  id: "cowpens-1781", name: "Cowpens, 17 January 1781", sides: ["Americans", "British"], table: "revolution-1775-83-all-hits",
  travel: { map: "cowpens-1781", place: "Hannah's Cowpens", within: 2, sides: ["Americans", "British"] },
  weather: "{cond: fair, wind: calm, dir: NW, ground: {mud: 0, snow: 0}}",
  grid, units,
  header: [
    `The field of Cowpens, 17 January 1781, at 10 m a hex: ${COLS} x ${ROWS} hexes, about 1200 m east to`,
    "west and 870 m north to south, north at the top, the British coming up from the south.",
    "Generated by tools/maps/make_cowpens_field.mjs: edit that file and re-run it rather than this one.",
    "The pasture, the two rises, the wet ravines and the woods are drawn by hand to the shape the",
    "accounts give, not traced from any map; the deployment is Morgan's three lines as most modern",
    "accounts give them, in our own words, with round numbers for play.",
    "",
    "What happened, briefly: Morgan drew up his riflemen in front, the militia behind them, and his",
    "Continentals on the crest, with Washington's horse out of sight behind the rise. He asked the",
    "riflemen and militia for two volleys each before falling back. Tarleton attacked at once after",
    "his night march. The skirmishers and militia fired and fell back round the Continentals' left.",
    "When an order to turn the right flank was taken as an order to retreat, the Continentals",
    "faced about, halted, turned and fired into the British coming on in disorder, and charged with",
    "the bayonet. Washington's horse came in from behind the rise and the militia came back round",
    "the other flank; the British line and the 71st were caught between them and surrendered.",
    "Tarleton escaped with most of his reserve horse. The morning was cold and clear.",
  ],
});
